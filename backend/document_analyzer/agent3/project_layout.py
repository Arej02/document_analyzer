"""Shared, pure facts about the assembled project's layout — design_agent3.md §5, §15.2, §15.3.

Used by stage `assemble` (which writes the tree), `final_test` (which writes the delivery
manifest) and `commit_plan.py` (which turns the manifest into commits). Keeping one copy
here is what makes "the tree at the last commit equals the zip" hold by construction
instead of by two code paths happening to agree. No DB, network or filesystem access.
"""

import re

UNIT_SLUG_PATTERN = re.compile(r"^[a-z0-9_]+$")

UNITS_INIT_PATH = "app/units/__init__.py"
