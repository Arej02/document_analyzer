# Files that sit at the project root and belong to the scaffold. Everything else in the
# scaffold is under `app/` or `tests/` (outside the per-unit directories) — see
# `scaffold_path_allowed`.
_SCAFFOLD_ROOT_FILES = frozenset({"pytest.ini", "requirements.txt", ".gitignore", CI_WORKFLOW_PATH})


def render_units_init(unit_slugs: list[str]) -> str:
    """§8's one unit-loading mechanism: imports exactly `unit_slugs`, in the order given.
    Stage `assemble` passes every unit; the commit plan passes the units committed so far,
    so every intermediate commit imports only files that exist in it."""
    lines = [
        '"""Written by stage `assemble` (design_agent3.md §5, §8): imports every '
        'unit, in plan order, so hook registrations run at startup."""',
        "",
        "import importlib",
        "",
    ]
    for slug in unit_slugs:
        lines.append(f"importlib.import_module({f'app.units.{slug}'!r})")
    return "\n".join(lines) + "\n"


def path_is_safe(path: str) -> bool:
    """A relative, forward-slash path with no empty, `.`, `..` or `.git` component and no
    control characters (a newline in a name would corrupt a line-oriented git stream)."""
    if not path or path.startswith("/") or "\\" in path or len(path) > 400:
        return False
    if any(ord(char) < 0x20 or ord(char) == 0x7F for char in path):
        return False
    return all(part not in ("", ".", "..", ".git") for part in path.split("/"))


def unit_path_allowed(path: str, unit_slug: str) -> bool:
    """§15.3: a unit's file must sit under its own `app/units/{slug}/` or `tests/units/{slug}/`
    (the same rule `generate.py` enforces) — never `.github/`, never another unit's directory,
    never the shared `app/units/__init__.py`."""
    if not path_is_safe(path) or not UNIT_SLUG_PATTERN.match(unit_slug):
        return False
    return path.startswith(f"app/units/{unit_slug}/") or path.startswith(f"tests/units/{unit_slug}/")


def scaffold_path_allowed(path: str) -> bool:
    """§15.3: a fixed allow-list. Template code under `app/` and `tests/` (but not the
    per-unit directories, which belong to units), plus a handful of fixed root files.
    `.github/` is allowed for exactly the one fixed workflow file."""
    if not path_is_safe(path):
        return False
    if path in _SCAFFOLD_ROOT_FILES:
        return True
    if path.startswith("app/units/") or path.startswith("tests/units/"):
        return False
    if path.startswith("app/") or path.startswith("tests/"):
        return True
    return False
