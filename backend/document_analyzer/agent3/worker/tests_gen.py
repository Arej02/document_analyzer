def _safe_ident(text: str) -> str:
    slug = _NON_IDENT.sub("_", text.lower()).strip("_")
    return slug or "x"


def _short_id(key: str) -> str:
    return hashlib.sha1(key.encode("utf-8")).hexdigest()[:8]


def _test_name(prefix: str, label: str, key: str) -> str:
    """A stable, unique, identifier-safe pytest test name: the same (label, key)
    pair always gives the same name, and two entries sharing a display label
    still land on distinct tests (a sha1 prefix of `key`, not a naive slice, so
    near-identical labels/ids don't collide)."""
    return f"test_{prefix}_{_safe_ident(label)}_{_short_id(key)}"


def _snake_case(name: str) -> str:
    """raw_facts.params gives raw PHP variable names (no `$`), possibly
    camelCase; design_agent3.md §6 ("params (snake_cased, defaults allowed)")."""
    return _CAMEL_BOUNDARY.sub("_", name).lower()


def _module_getattr_lines(module: str, python_name: str, kind: str) -> list[str]:
    """§4 step 2 / §6: `kind = method` symbols use the dotted `ClassName.method_name`
    convention (design_agent3.md §6, 2026-09-28) — resolve the class first, then
    the method on it, so a method that landed on the wrong class fails here."""
    lines = [f"    module = importlib.import_module({module!r})"]
    if kind == "method":
        class_name, _, method_name = python_name.partition(".")
        lines += [
            f"    cls = getattr(module, {class_name!r}, None)",
            f"    assert cls is not None, {(module + '.' + class_name + ' not found')!r}",
            f"    assert hasattr(cls, {method_name!r}), "
            f"{(python_name + ' not defined on the mapped class')!r}",
            f"    obj = getattr(cls, {method_name!r})",
        ]
    else:
        lines += [
            f"    obj = getattr(module, {python_name!r}, None)",
            f"    assert obj is not None, {(module + '.' + python_name + ' not found')!r}",
        ]
    return lines


def _param_check_lines(expected: list[str]) -> list[str]:
    return [
        "    assert callable(obj)",
        "    _names = [p for p in inspect.signature(obj).parameters if p not in ('self', 'cls')]",
        f"    _expected = {expected!r}",
        "    assert _names[: len(_expected)] == _expected, "
        "'expected leading params %r, got %r' % (_expected, _names)",
    ]


def _render(name: str, body_lines: list[str]) -> str:
    return "\n".join(["@pytest.mark.contract", f"def {name}():", *body_lines])


def _public_interface_tests(test_contract: dict, symbol_map: dict) -> list[str]:
    tests = []
    for entry in sorted(test_contract.get("public_interface") or [], key=lambda e: e["entity_id"]):
        entity_id = entry["entity_id"]
        test_name = _test_name("public_interface", entry.get("name") or entity_id, entity_id)
        symbol = symbol_map.get(entity_id)
        if symbol is None:
            body = [f"    pytest.fail({('symbol_map is missing public_interface entity ' + entity_id)!r})"]
        else:
            kind = symbol.get("kind") or entry.get("kind") or "function"
            expected = [_snake_case(p) for p in (entry.get("params") or []) if p]
            body = _module_getattr_lines(symbol["python_module"], symbol["python_name"], kind)
            body += _param_check_lines(expected)
        tests.append(_render(test_name, body))
    return tests


def _incoming_call_site_tests(test_contract: dict, symbol_map: dict) -> list[str]:
    names_by_id = {e["entity_id"]: e.get("name") for e in (test_contract.get("public_interface") or [])}
    entity_ids = sorted({site["to_entity_id"] for site in (test_contract.get("incoming_call_sites") or [])})
    tests = []
    for entity_id in entity_ids:
        label = names_by_id.get(entity_id) or entity_id
        test_name = _test_name("incoming_call_site", label, entity_id)
        symbol = symbol_map.get(entity_id)
        if symbol is None:
            body = [f"    pytest.fail({('symbol_map is missing incoming call target ' + entity_id)!r})"]
        else:
            kind = symbol.get("kind") or "function"
            body = _module_getattr_lines(symbol["python_module"], symbol["python_name"], kind)
            body.append("    assert callable(obj)")
        tests.append(_render(test_name, body))
    return tests


def _outgoing_dependency_tests(unit_slug: str, test_contract: dict, dependencies: list[dict]) -> list[str]:
    deps_by_unit = {d["to_unit_id"]: d for d in dependencies}
    tests = []
    for dep in sorted(test_contract.get("outgoing_dependencies") or [], key=lambda d: d["to_unit_id"]):
        to_unit_id = dep["to_unit_id"]
        test_name = _test_name("outgoing_dependency", to_unit_id, to_unit_id)
        dep_symbol_map = (deps_by_unit.get(to_unit_id) or {}).get("symbol_map") or {}
        if not dep_symbol_map:
            # A dependency with no symbol map yet is a not-yet-generated or
            # `error` unit (design_agent3.md §4 "failed dependencies"): a stub
            # module stands in for it by the time this test actually runs, but
            # there's nothing here to check against yet.
            tests.append(
                _render(test_name, [f"    pytest.skip({('dependency ' + to_unit_id + ' has no symbol map yet')!r})"])
            )
            continue

        # A method's redefinable surface is its class name (re-implementing a
        # method means redefining the whole class), not the dotted "Class.method".
        redefinable = sorted(
            {
                (s["python_name"].partition(".")[0] if s.get("kind") == "method" else s["python_name"])
                for s in dep_symbol_map.values()
            }
        )
        body = [
            f"    forbidden = {redefinable!r}",
            f"    shadowed = sorted(set(_unit_top_level_names({unit_slug!r})) & set(forbidden))",
            "    assert not shadowed, "
            "'re-implements %r instead of importing them from the dependency' % (shadowed,)",
        ]
        if (dep.get("call_count") or 0) or (dep.get("hook_binding_count") or 0):
            modules = sorted({s["python_module"] for s in dep_symbol_map.values()})
            body += [
                f"    source = _unit_source_text({unit_slug!r})",
                f"    expected_modules = {modules!r}",
                "    assert any(m in source for m in expected_modules), "
                "'dependency module never referenced: %r' % (expected_modules,)",
            ]
        tests.append(_render(test_name, body))
    return tests


def _external_call_tests(unit_slug: str, test_contract: dict) -> list[str]:
    tests = []
    for name in sorted(set(test_contract.get("external_calls") or [])):
        test_name = _test_name("external_call", name, name)
        body = [
            f"    assert {name!r} not in _unit_top_level_names({unit_slug!r}), "
            f"{(name + ' is reimplemented instead of routed through app.wp_compat')!r}",
            f"    _, flat_names = _wp_compat_bindings({unit_slug!r})",
            f"    bare_calls = _bare_calls({unit_slug!r}, {name!r})",
            "    if bare_calls:",
            f"        assert {name!r} in flat_names, "
            f"{(name + ' is called without importing it from app.wp_compat')!r}",
        ]
        tests.append(_render(test_name, body))
    return tests


def _hooks_bound_tests(unit_slug: str, test_contract: dict) -> list[str]:
    tests = []
    for hook_name in sorted(set(test_contract.get("hooks_bound") or [])):
        test_name = _test_name("hook_bound", hook_name, hook_name)
        body = [
            f"    importlib.import_module({('app.units.' + unit_slug)!r})",
            "    from app.events import handlers_for",
            f"    assert handlers_for({hook_name!r}), {('no handler registered for hook ' + hook_name)!r}",
        ]
        tests.append(_render(test_name, body))
    return tests


def _routes_bound_tests(unit_slug: str, test_contract: dict) -> list[str]:
    tests = []
    for route in sorted(set(test_contract.get("routes_bound") or [])):
        method, _, path = route.partition(" ")
        test_name = _test_name("route_bound", route, route)
        body = [
            f"    module = importlib.import_module({('app.units.' + unit_slug)!r})",
            "    router = getattr(module, 'router', None)",
            f"    assert router is not None, {('app.units.' + unit_slug + ' has no router attribute')!r}",
            f"    _method, _path = {method!r}, {path!r}",
            "    _matched = any(",
            "        _path == getattr(r, 'path', None) and _method in (getattr(r, 'methods', None) or set())",
            "        for r in router.routes",
            "    )",
            f"    assert _matched, {('no route bound for ' + route)!r}",
        ]
        tests.append(_render(test_name, body))
    return tests


def generate_contract_tests(
    unit_slug: str,
    test_contract: dict,
    symbol_map: dict,
    dependencies: list[dict],
) -> list[GeneratedFile]:
    """design_agent3.md §6. `dependencies` is `UnitContext.dependencies` (§4 step 1):
    each entry's own `symbol_map`, already known for every earlier-finished unit.
    Returns a single file, `tests/units/{unit_slug}/test_contract.py`."""
    test_contract = test_contract or {}
    symbol_map = symbol_map or {}
    dependencies = dependencies or []

    tests: list[str] = []
    tests += _public_interface_tests(test_contract, symbol_map)
    tests += _incoming_call_site_tests(test_contract, symbol_map)
    tests += _outgoing_dependency_tests(unit_slug, test_contract, dependencies)
    tests += _external_call_tests(unit_slug, test_contract)
    tests += _hooks_bound_tests(unit_slug, test_contract)
    tests += _routes_bound_tests(unit_slug, test_contract)
    # side_effect_signals / unverified_member_ids / merged_cluster_ids: no test (§6).

    content = _PREAMBLE + "\n\n" + "\n\n\n".join(tests) + "\n"
    return [GeneratedFile(path=f"tests/units/{unit_slug}/test_contract.py", content=content)]


