BEHAVIOUR_TEST_RULES = """You are writing pytest behaviour tests for one migration unit's generated Python \
code (design_agent3.md Section 6). You are given the unit's legacy PHP source and facts, its test contract, a \
report describing what it does, and the Python code just generated for it (paths under \
app/units/<unit_slug>/, plus a symbol_map naming where each public symbol landed). Write tests that check \
what the code actually does, not just its shape — contract tests already check imports, signatures and \
wiring separately, so do not repeat those.

Follow these rules exactly:
- Mark every test function `@pytest.mark.behaviour`.
- Resolve the unit's own module, and any dependency's module, with `importlib.import_module("...")` (a plain \
string) — never a literal `import`/`from` statement. `unit_slug` starts with a digit (for example \
"01_01_cart"), so `from app.units.01_01_cart.module import x` is a SyntaxError.
- Every test runs against the fake wp_compat backend by default (autouse) — there is no network in the \
sandbox. To check a side effect, request the `wp_compat_fake` fixture by name and assert on its `.calls` list \
(each entry is `(function_name, args, kwargs)`).
- For every member listed in the contract's `side_effect_signals`, you MUST assert on `wp_compat_fake.calls` \
or on persisted state (the `db_session` fixture) — never only on the function's return value.
- A test that specifically needs real, DB-backed wp_compat behavior (for example checking a value survives \
across two calls) can request the `real_wp_compat` fixture instead of `wp_compat_fake`.

Respond with a single JSON object and nothing else, in this exact shape:
{"content": "<the full contents of tests/units/<unit_slug>/test_behaviour.py>"}"""


class _BehaviourValidationFailure(Exception):
    """One attempt's response didn't validate; drives the retry loop, never escapes this module."""


@dataclass(frozen=True)
class BehaviourTestResult:
    """§4 step 3 / FR5. `generated=False` (always with `files=[]`) means every attempt was
    invalid and generation was abandoned — a unit-level outcome to record, never raised
    (CLAUDE.md "grounding failures never block": the unit's own generated code and its
    deterministic contract tests are unaffected). Stage `units` (next task) uses this to
    set `test_summary.behaviour` — the normal `{passed, failed}` shape once the sandbox
    has run real tests, or `{"passed": 0, "failed": 0, "generated": False}` when there is
    nothing to run, so a reviewer can see that `side_effect_signals` went unchecked for
    this unit without a new `unit_executions.flags` value (that column has a fixed DB
    check constraint; `test_summary` is free-form jsonb)."""

    files: list[GeneratedFile] = field(default_factory=list)
    generated: bool = True
    attempts: int = 0


def _is_behaviour_mark(node: ast.expr) -> bool:
    """Matches the decorator `@pytest.mark.behaviour` exactly (an attribute access
    chain), the only spelling the prompt asks for."""
    return (
        isinstance(node, ast.Attribute)
        and node.attr == "behaviour"
        and isinstance(node.value, ast.Attribute)
        and node.value.attr == "mark"
        and isinstance(node.value.value, ast.Name)
        and node.value.value.id == "pytest"
    )


def _validate_behaviour_markers(tree: ast.Module) -> None:
    for node in ast.iter_child_nodes(tree):
        if isinstance(node, (ast.FunctionDef, ast.AsyncFunctionDef)) and node.name.startswith("test_"):
            if not any(_is_behaviour_mark(d) for d in node.decorator_list):
                raise _BehaviourValidationFailure(f"{node.name} is not marked @pytest.mark.behaviour")


def _validate_behaviour_response(content: str | None) -> str:
    try:
        parsed = json.loads(content) if content is not None else None
    except json.JSONDecodeError as exc:
        raise _BehaviourValidationFailure(f"response was not valid JSON: {content!r}") from exc
    if not isinstance(parsed, dict) or not isinstance(parsed.get("content"), str) or not parsed["content"].strip():
        raise _BehaviourValidationFailure(f"response JSON must be {{'content': non-empty str}}: {parsed!r}")

    source = parsed["content"]
    try:
        tree = ast.parse(source)
    except SyntaxError as exc:
        raise _BehaviourValidationFailure(f"test_behaviour.py does not parse as Python: {exc}") from exc
    _validate_behaviour_markers(tree)
    return source


def _initial_behaviour_messages(context: UnitContext, unit_slug: str, generated: GeneratedUnit) -> list[dict]:
    system = f"{BEHAVIOUR_TEST_RULES}\n\nYour unit_slug is: {unit_slug}"
    generated_payload = json.dumps(
        {
            "files": [{"path": f.path, "content": f.content} for f in generated.files],
            "symbol_map": generated.symbol_map,
        },
        sort_keys=True,
    )
    user = context.text + "\n\nGenerated code:\n" + generated_payload
    return [
        {"role": "system", "content": system},
        {"role": "user", "content": user},
    ]


def generate_behaviour_tests(
    context: UnitContext,
    unit_slug: str,
    generated: GeneratedUnit,
    llm_client: AzureOpenAI,
    model_deployment: str,
    max_attempts: int,
) -> BehaviourTestResult:
    """design_agent3.md §4 step 3, specs FR5. Never raises: exhausting every attempt
    returns `BehaviourTestResult(files=[], generated=False, ...)` rather than a
    `GenerationError` — see `BehaviourTestResult`'s docstring."""
    messages = _initial_behaviour_messages(context, unit_slug, generated)

    for attempt in range(1, max_attempts + 1):
        response = llm_client.chat.completions.create(
            model=model_deployment,
            response_format={"type": "json_object"},
            messages=messages,
        )
        content = response.choices[0].message.content
        try:
            source = _validate_behaviour_response(content)
        except _BehaviourValidationFailure as exc:
            problem = str(exc)
            messages = [
                *messages,
                {"role": "assistant", "content": content or ""},
                {
                    "role": "user",
                    "content": f"That response was invalid: {problem}. Fix it and respond again with the "
                    "same JSON shape and nothing else.",
                },
            ]
            continue
        return BehaviourTestResult(
            files=[GeneratedFile(path=f"tests/units/{unit_slug}/test_behaviour.py", content=source)],
            generated=True,
            attempts=attempt,
        )

    return BehaviourTestResult(files=[], generated=False, attempts=max_attempts)
